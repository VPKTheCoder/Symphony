def _git_files(root: Path) -> list[Path]:
    """List Rust files through Git so tracked and untracked .gitignore rules apply."""

    result = subprocess.run(
        ["git", "-C", str(root), "ls-files", "--cached", "--others", "--exclude-standard", "-z"],
        check=False,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )
    if result.returncode == 0:
        candidates = [root / os.fsdecode(item) for item in result.stdout.split(b"\0") if item]
    else:
        # Non-Git Rust folders are still useful, with common ignore rules and
        # the root .gitignore applied as a conservative fallback.
        ignored: list[str] = []
        ignore_file = root / ".gitignore"
        if ignore_file.exists():
            ignored = [
                line.strip().replace("\\", "/")
                for line in ignore_file.read_text(encoding="utf-8", errors="ignore").splitlines()
                if line.strip() and not line.lstrip().startswith("#") and not line.startswith("!")
            ]
        candidates = []
        for path in root.rglob("*.rs"):
            rel = path.relative_to(root).as_posix()
            if any(fnmatch.fnmatch(rel, pat) or fnmatch.fnmatch(rel, f"**/{pat}") for pat in ignored):
                continue
            candidates.append(path)

    kept: list[Path] = []
    for path in candidates:
        if path.suffix != ".rs" or not path.is_file():
            continue
        parts = {part.lower() for part in path.relative_to(root).parts}
        if parts & {"target", "vendor", "build"} or path.name == "build.rs":
            continue
        kept.append(path)
    return sorted(set(kept), key=lambda item: item.relative_to(root).as_posix().casefold())


def _workspace_crates(root: Path, rust_files: list[Path]) -> list[tuple[str, Path]]:
    manifest_set = {root / "Cargo.toml"}
    for rust_path in rust_files:
        parent = rust_path.parent
        while parent == root or root in parent.parents:
            manifest_set.add(parent / "Cargo.toml")
            if parent == root:
                break
            parent = parent.parent
    manifests = sorted(
        (path for path in manifest_set if path.exists()),
        key=lambda path: path.as_posix().casefold(),
    )
    root_manifest = root / "Cargo.toml"
    crate_dirs: dict[Path, str] = {}

    def add_package(manifest: Path) -> None:
        try:
            data = tomllib.loads(manifest.read_text(encoding="utf-8"))
        except (OSError, tomllib.TOMLDecodeError):
            return
        package = data.get("package")
        if isinstance(package, dict) and package.get("name"):
            crate_dirs[manifest.parent.resolve()] = str(package["name"]).replace("-", "_")

    if root_manifest.exists():
        try:
            root_data = tomllib.loads(root_manifest.read_text(encoding="utf-8"))
        except (OSError, tomllib.TOMLDecodeError):
            root_data = {}
        add_package(root_manifest)
        workspace = root_data.get("workspace", {})
        for member_pattern in workspace.get("members", []) if isinstance(workspace, dict) else []:
            for candidate in sorted(root.glob(str(member_pattern))):
                manifest = candidate / "Cargo.toml" if candidate.is_dir() else candidate
                if manifest.name == "Cargo.toml" and manifest.exists():
                    add_package(manifest)
    if not crate_dirs:
        for manifest in manifests:
            add_package(manifest)
    if not crate_dirs:
        crate_dirs[root.resolve()] = root.name.replace("-", "_") or "crate"

    # A workspace root may itself be a virtual manifest. Only include members
    # containing discovered Rust sources; preserve package-name prefixes.
    assignments = []
    for crate_dir, name in sorted(crate_dirs.items(), key=lambda item: item[0].as_posix().casefold()):
        if any(path.is_relative_to(crate_dir) for path in rust_files):
            assignments.append((name, crate_dir))
    return assignments or [(root.name.replace("-", "_") or "crate", root.resolve())]


@lru_cache(maxsize=None)
def _crate_roots(crate_dir: str) -> tuple[tuple[str, str], ...]:
    base = Path(crate_dir)
    targets: dict[str, str] = {
        "src/main.rs": "main",
        "src/lib.rs": "lib",
    }
    manifest = base / "Cargo.toml"
    if manifest.exists():
        try:
            data = tomllib.loads(manifest.read_text(encoding="utf-8"))
        except (OSError, tomllib.TOMLDecodeError):
            data = {}
        lib = data.get("lib")
        if isinstance(lib, dict) and lib.get("path"):
            targets[str(lib["path"]).replace("\\", "/")] = "lib"
        bins = data.get("bin", [])
        if isinstance(bins, list):
            for index, item in enumerate(bins):
                if isinstance(item, dict) and item.get("path"):
                    targets[str(item["path"]).replace("\\", "/")] = f"bin_{item.get('name', index)}"
    return tuple(sorted(targets.items()))


def _module_for_path(path: Path, crate_dir: Path, crate: str) -> str:
    rel = path.relative_to(crate_dir).as_posix().split("/")
    target_roots = _crate_roots(str(crate_dir))
    for target_path, module_name in target_roots:
        normalized = target_path.split("/")
        if rel == normalized:
            return f"{crate}::{module_name}"
        nested_root = crate_dir / Path(target_path).with_suffix("")
        if path.is_relative_to(nested_root):
            nested = list(path.relative_to(nested_root).as_posix().split("/"))
            if nested[-1].endswith(".rs"):
                nested[-1] = nested[-1][:-3]
            if nested[-1] == "mod":
                nested.pop()
            return "::".join([crate, *[part for part in nested if part]])
    custom_dirs = [
        (Path(target_path).parent, module_name)
        for target_path, module_name in target_roots
        if not target_path.startswith("src/") and Path(target_path).parent.parts
    ]
    matching_dirs = [directory for directory, _ in custom_dirs if path.is_relative_to(crate_dir / directory)]
    if matching_dirs:
        source_dir = max(matching_dirs, key=lambda item: len(item.parts))
        rel = list(path.relative_to(crate_dir / source_dir).as_posix().split("/"))
    elif rel[0] == "src":
        rel = rel[1:]
    elif rel[0] in {"tests", "examples", "benches"}:
        rel = [rel[0], *rel[1:]]
    else:
        rel = ["src", *rel]
    if rel and rel[-1].endswith(".rs"):
        rel[-1] = rel[-1][:-3]
    if rel and rel[-1] == "mod":
        rel.pop()
    if len(rel) == 2 and rel[0] == "bin":
        parts = ["bin_" + rel[1]]
    elif len(rel) >= 3 and rel[0] == "bin" and rel[2] == "main":
        parts = ["bin_" + rel[1], *rel[3:]]
    elif rel and rel[-1] in {"main", "lib"} and len(rel) == 1:
        parts = rel
    elif rel and rel[-1] == "main" and len(rel) >= 2 and rel[-2] == "bin":
        parts = ["bin_" + (rel[-3] if len(rel) >= 3 else "main")]
    elif rel and rel[-1] == "bin":
        parts = ["bin"]
    else:
        parts = rel
    return "::".join([crate, *[part for part in parts if part]])


def _visible(node: Node, source: bytes) -> bool:
    return any(child.type == "visibility_modifier" for child in node.children) or bool(
        re.search(rb"\bpub\b", source[node.start_byte : min(node.end_byte, node.start_byte + 32)])
    )


def _has_attribute(attributes: Iterable[bytes], name: str) -> bool:
    return any(re.search(rb"#\s*\[\s*(?:[A-Za-z_][\w:]*::)?" + name.encode() + rb"\b", attr) for attr in attributes)


def _is_comment(node: Node) -> bool:
    return node.type == "comment" or node.type.endswith("_comment")


def _path_tokens(text: str, crate: str) -> list[str]:
    tokens = _PATH_TOKEN.findall(text)
    tokens.extend(
        re.findall(
            rf"(?<![A-Za-z0-9_]){re.escape(crate)}(?:::(?:[A-Za-z_][A-Za-z0-9_]*|\*))+",
            text,
        )
    )
    return list(dict.fromkeys(tokens))


def _resolve_source_references(text: str, current: str, crate: str, known: set[str]) -> list[str]:
    resolved = []
    for token in _path_tokens(text, crate):
        target = _resolve_reference(token, current, known)
        if target and target not in resolved:
            resolved.append(target)
    bare_paths = re.findall(r"(?<![A-Za-z0-9_])([A-Za-z_][A-Za-z0-9_]*(?:::[A-Za-z_][A-Za-z0-9_]*)+)", text)
    candidates = sorted(
        (
            module
            for module in known
            if module.startswith(crate + "::") and module != current
        ),
        key=lambda module: (-len(module), module),
    )
    for token in bare_paths:
        for module in candidates:
            relative = module[len(crate) + 2 :]
            prefixes = [relative + "::"]
            current_relative = current[len(crate) + 2 :] if current.startswith(crate + "::") else ""
            if current_relative and relative.startswith(current_relative + "::"):
                prefixes.append(relative[len(current_relative) + 2 :] + "::")
            if any(token.startswith(prefix) for prefix in prefixes):
                if module not in resolved:
                    resolved.append(module)
                break
    return resolved


def _count_function_branches(node: Node, source: bytes) -> int:
    count = 0
    stack = list(reversed(node.children))
    while stack:
        child = stack.pop()
        if child is not node and child.type == "function_item":
            continue
        if child.type == "if_expression":
            count += 1
        elif child.type == "match_arm":
            count += 1
        elif child.type in {"for_expression", "while_expression", "loop_expression"}:
            count += 1
        elif child.type == "try_expression":
            count += 1
        elif child.type == "binary_expression":
            count += sum(grandchild.type in {"&&", "||"} for grandchild in child.children)
        stack.extend(reversed(child.children))
    return count


def _source_loc(source: bytes, start_line: int, end_line: int) -> int:
    lines = source.splitlines()
    loc = 0
    for index in range(max(0, start_line), min(len(lines), end_line)):
        stripped = lines[index].strip()
        if stripped and not stripped.startswith((b"//", b"/*", b"*", b"*/")):
            loc += 1
    return loc


def _parse_lcov(path: Path, root: Path, file_to_modules: dict[str, set[str]]) -> dict[str, list[tuple[int, int]]]:
    result: dict[str, list[tuple[int, int]]] = defaultdict(list)
    current: str | None = None
    if not path.exists():
        raise ValueError(f"LCOV file does not exist: {path}")
    for line in path.read_text(encoding="utf-8", errors="replace").splitlines():
        if line.startswith("SF:"):
            current = line[3:]
        elif line.startswith("DA:") and current:
            try:
                _, hits = line[3:].split(",", 1)
                count = int(hits.split(",", 1)[0])
            except ValueError:
                continue
            candidates = {Path(current).as_posix().casefold(), Path(current).name.casefold()}
            try:
                candidates.add((root / current).resolve().relative_to(root.resolve()).as_posix().casefold())
            except (OSError, ValueError):
                pass
            for candidate in candidates:
                for module_name in file_to_modules.get(candidate, ()):
                    result[module_name].append((1, int(count > 0)))
        elif line == "end_of_record":
            current = None
    return result


def _normalize_complexities(raw: dict[str, int]) -> dict[str, float]:
    values = list(raw.values())
    if not values or max(values) == 0:
        return {name: 0.0 for name in raw}
    unique_values = sorted(set(values))
    if len(unique_values) == 1:
        rank_values = {unique_values[0]: 0.5}
    else:
        rank_values = {
            value: index / (len(unique_values) - 1)
            for index, value in enumerate(unique_values)
        }
    # The rank term spreads tied light modules; log scaling keeps one huge
    # function from crushing the differences among the rest of the repo.
    log_max = math.log1p(max(values))
    return {
        name: min(1.0, max(0.0, 0.55 * math.log1p(value) / log_max + 0.45 * rank_values[value]))
        for name, value in raw.items()
    }


_ITERATOR_METHODS = {
    "all", "any", "by_ref", "chain", "cloned", "collect", "copied",
    "enumerate", "filter", "filter_map", "find", "flat_map", "flatten",
    "fold", "for_each", "inspect", "into_iter", "iter", "iter_mut", "map",
    "max", "min", "peekable", "reduce", "rev", "skip", "take", "zip",
}


def _iterator_chain_length(node: Node, source: bytes) -> int:
    """Count consecutive iterator adaptor/terminal calls on one receiver."""

    if node.type != "call_expression":
        return max((_iterator_chain_length(child, source) for child in node.children), default=0)
    function = node.child_by_field_name("function")
    if function is not None and function.type == "generic_function":
        function = function.child_by_field_name("function")
    if function is None or function.type != "field_expression":
        return max((_iterator_chain_length(child, source) for child in node.children), default=0)
    field = function.child_by_field_name("field")
    receiver = function.child_by_field_name("value")
    name = source[field.start_byte : field.end_byte].decode("utf-8", "replace") if field else ""
    preceding = _iterator_chain_length(receiver, source) if receiver else 0
    return preceding + 1 if name in _ITERATOR_METHODS else preceding


def _collect_rust_features(root: Node, source: bytes) -> dict[str, int]:
    counts = {
        "trait_count": 0,
        "impl_count": 0,
        "generic_parameter_count": 0,
        "lifetime_count": 0,
        "macro_rules_count": 0,
        "proc_macro_use_count": 0,
        "macro_invocation_count": 0,
        "async_fn_count": 0,
        "try_operator_count": 0,
        "unwrap_call_count": 0,
        "expect_call_count": 0,
        "panic_call_count": 0,
        "closure_count": 0,
        "max_iterator_chain_length": 0,
        "clone_call_count": 0,
        "pub_api_count": 0,
        "function_count": 0,
        "item_count": 0,
        "total_loc": 0,
    }
    public_items = {
        "function_item", "struct_item", "enum_item", "union_item", "trait_item",
        "type_item", "const_item", "static_item", "mod_item",
    }
    stack = [root]
    while stack:
        node = stack.pop()
        node_type = node.type
        if node_type in {"trait_item", "impl_item"}:
            counts["trait_count" if node_type == "trait_item" else "impl_count"] += 1
        elif node_type in {"type_parameter", "const_parameter", "lifetime_parameter"}:
            counts["generic_parameter_count"] += 1
        elif node_type == "lifetime":
            counts["lifetime_count"] += 1
        elif node_type == "macro_definition":
            counts["macro_rules_count"] += 1
        elif node_type == "macro_invocation":
            counts["macro_invocation_count"] += 1
            macro = node.child_by_field_name("macro")
            macro_name = source[macro.start_byte : macro.end_byte] if macro else b""
            if macro_name == b"panic":
                counts["panic_call_count"] += 1
        elif node_type == "attribute_item":
            value = source[node.start_byte : node.end_byte]
            if re.search(rb"\bproc_macro(?:_attribute|_derive)?\b", value):
                counts["proc_macro_use_count"] += 1
        elif node_type == "function_item":
            counts["function_count"] += 1
            modifiers = node.child_by_field_name("function_modifiers")
            # Grammar versions differ in whether modifiers are addressable by field.
            if (modifiers and b"async" in source[modifiers.start_byte : modifiers.end_byte]) or any(
                child.type == "function_modifiers" and b"async" in source[child.start_byte : child.end_byte]
                for child in node.children
            ):
                counts["async_fn_count"] += 1
        elif node_type == "try_expression":
            counts["try_operator_count"] += 1
        elif node_type == "closure_expression":
            counts["closure_count"] += 1
        elif node_type == "call_expression":
            function = node.child_by_field_name("function")
            if function and function.type == "field_expression":
                field = function.child_by_field_name("field")
                method = source[field.start_byte : field.end_byte].decode("utf-8", "replace") if field else ""
                if method in {"unwrap", "expect", "clone"}:
                    counts[{"unwrap": "unwrap_call_count", "expect": "expect_call_count", "clone": "clone_call_count"}[method]] += 1
            counts["max_iterator_chain_length"] = max(
                counts["max_iterator_chain_length"], _iterator_chain_length(node, source)
            )
        if node_type in public_items:
            counts["item_count"] += 1
            if _visible(node, source):
                counts["pub_api_count"] += 1
        stack.extend(reversed(node.children))
    counts["total_loc"] = len(source.splitlines())
    return counts


def _rust_feature_profile(counts: dict[str, int], modules: dict[str, _Module], depended_by: dict[str, int]) -> dict[str, float | int]:
    functions = max(1, counts["function_count"])
    loc = max(1, counts["total_loc"])
    all_edges = sum(depended_by.values())
    top_incoming = max(depended_by.values(), default=0)
    result: dict[str, float | int] = dict(counts)
    result.update(
        {
            "traits_per_100_functions": round(100 * counts["trait_count"] / functions, 6),
            "impls_per_100_functions": round(100 * counts["impl_count"] / functions, 6),
            "generics_per_100_functions": round(100 * counts["generic_parameter_count"] / functions, 6),
            "lifetimes_per_100_functions": round(100 * counts["lifetime_count"] / functions, 6),
            "macros_per_kloc": round(1000 * (counts["macro_rules_count"] + counts["macro_invocation_count"] + counts["proc_macro_use_count"]) / loc, 6),
            "async_fn_ratio": round(counts["async_fn_count"] / functions, 6),
            "try_operators_per_100_functions": round(100 * counts["try_operator_count"] / functions, 6),
            "unwrap_expect_panic_per_100_functions": round(100 * (counts["unwrap_call_count"] + counts["expect_call_count"] + counts["panic_call_count"]) / functions, 6),
            "closures_per_100_functions": round(100 * counts["closure_count"] / functions, 6),
            "clone_calls_per_100_functions": round(100 * counts["clone_call_count"] / functions, 6),
            "pub_api_ratio": round(counts["pub_api_count"] / max(1, counts["item_count"]), 6),
            "max_module_depth": max((max(0, len(module.name.split("::")) - 1) for module in modules.values()), default=0),
            "dependency_hub_concentration": round(top_incoming / max(1, all_edges), 6),
        }
    )
    return result


def _resolve_reference(token: str, current: str, known: set[str]) -> str | None:
    segments = token.split("::")
    if not segments:
        return None
    if segments[0] == "crate":
        candidates = ["::".join(segments[:end]) for end in range(len(segments), 1, -1)]
    elif segments[0] == current.split("::", 1)[0]:
        candidates = ["::".join(segments[:end]) for end in range(len(segments), 1, -1)]
    elif segments[0] == "self":
        prefix = current.split("::")
        candidates = ["::".join(prefix + segments[1 : end]) for end in range(len(segments), 1, -1)]
    else:  # one or more super:: segments
        prefix = current.split("::")
        while segments and segments[0] == "super":
            if len(prefix) > 1:
                prefix.pop()
            segments.pop(0)
        candidates = ["::".join(prefix + segments[:end]) for end in range(len(segments), 0, -1)]
        if segments == ["*"]:
            candidates.insert(0, "::".join(prefix))
    return next((candidate for candidate in candidates if candidate in known and candidate != current), None)


def _declared_child(current: str, record: _RustFile, child: str) -> str:
    """Resolve a module declared by an entry file at the crate root."""

    relative_file = record.path.relative_to(record.crate_dir).as_posix()
    root_file = relative_file in dict(_crate_roots(str(record.crate_dir)))
    if root_file and current == record.module:
        relative = record.path.relative_to(record.crate_dir).as_posix()
        is_separate_bin = relative.startswith("src/bin/") and current.rsplit("::", 1)[-1].startswith("bin_")
        prefix = current if is_separate_bin else record.crate
    else:
        prefix = current
    return f"{prefix}::{child}"


def _compress_modules(modules: dict[str, _Module], limit: int = 14) -> dict[str, str]:
    aliases = {name: name for name in modules}
    while len(modules) > limit:
        candidates = sorted(
            (item for item in modules.values() if item.name.count("::") > 0 and not item.name.endswith("::other")),
            key=lambda item: (item.loc, item.declaration_order, item.name),
        )
        if not candidates:
            break
        item = candidates[0]
        parent = item.name.rsplit("::", 1)[0]
        target_name = parent if parent in modules and parent != item.name else f"{item.crate}::other"
        if target_name == item.name:
            break
        if target_name not in modules:
            modules[target_name] = _Module(target_name, item.crate, item.declaration_order)
        target = modules[target_name]
        target.loc += item.loc
        target.raw_complexity += item.raw_complexity
        target.function_count += item.function_count
        target.contains_main = target.contains_main or item.contains_main
        target.public_function_count += item.public_function_count
        target.test_function_count += item.test_function_count
        target.unsafe_count += item.unsafe_count
        target.todo_count += item.todo_count
        target.line_coverage.extend(item.line_coverage)
        target.dependencies.extend(dep for dep in item.dependencies if dep not in target.dependencies)
        target.declared_dependencies.extend(
            dep for dep in item.declared_dependencies if dep not in target.declared_dependencies
        )
        target.dependency_files.update(item.dependency_files)
        target.test_targets.update(item.test_targets)
        for old_name, new_name in list(aliases.items()):
            if new_name == item.name or new_name.startswith(item.name + "::"):
                aliases[old_name] = target_name
        del modules[item.name]
    return aliases


def analyze_repository(
    repository: str | Path,
    *,
    name: str | None = None,
    entry: str | None = None,
    lcov: str | Path | None = None,
) -> dict:
    """Analyze a Rust project and return a deterministic composer profile."""

    root = Path(repository).expanduser().resolve()
    if not root.is_dir():
        raise ValueError(f"Rust repository directory not found: {root}")
    paths = _git_files(root)
    if not paths:
        raise ValueError(f"No non-generated Rust source files found under {root}")
    crates = _workspace_crates(root, paths)
    try:
        root_package = tomllib.loads((root / "Cargo.toml").read_text(encoding="utf-8")).get("package", {})
    except (OSError, tomllib.TOMLDecodeError):
        root_package = {}
    root_crate = str(root_package.get("name", crates[0][0])).replace("-", "_") if crates else root.name

    file_records: list[_RustFile] = []
    file_to_modules: dict[str, set[str]] = defaultdict(set)
    modules: dict[str, _Module] = {}
    rust_feature_counts: dict[str, int] = defaultdict(int)
    declaration_order = 0
    for path in paths:
        crate_match = next(
            ((crate, crate_dir) for crate, crate_dir in reversed(crates) if path.is_relative_to(crate_dir)),
            None,
        )
        if not crate_match:
            continue
        crate, crate_dir = crate_match
        try:
            source = path.read_bytes()
        except OSError:
            continue
        header = source[:8192].lower()
        if any(marker.encode() in header for marker in _GENERATED_MARKERS):
            continue
        module = _module_for_path(path, crate_dir, crate)
        file_records.append(_RustFile(path, crate, crate_dir, module, source))
        relative = path.relative_to(root).as_posix().casefold()
        file_to_modules[relative].add(module)
        file_to_modules[path.name.casefold()].add(module)
        if module not in modules:
            modules[module] = _Module(module, crate, declaration_order)
            declaration_order += 1

    if not file_records:
        raise ValueError(f"No parseable Rust source files found under {root}")

    # First pass: tree-sitter syntax nodes drive metrics, nested inline module
    # ownership, test scope, and declared module edges.
    parser = Parser(_RUST)
    for record in file_records:
        source = record.source
        tree = parser.parse(source)
        if tree is None:
            continue
        file_features = _collect_rust_features(tree.root_node, source)
        for feature, value in file_features.items():
            if feature == "max_iterator_chain_length":
                rust_feature_counts[feature] = max(rust_feature_counts[feature], value)
            else:
                rust_feature_counts[feature] += value
        modules[record.module].dependency_files.add(record.path.as_posix())

        def ensure_module(module_name: str, crate: str) -> _Module:
            nonlocal declaration_order
            if module_name not in modules:
                modules[module_name] = _Module(module_name, crate, declaration_order)
                declaration_order += 1
            return modules[module_name]

        def visit(parent: Node, current: str, in_test_scope: bool = False) -> None:
            stack = [(parent, current, in_test_scope)]
            in_tests_dir = "tests" in record.path.relative_to(root).parts
            while stack:
                current_parent, current_name, test_scope = stack.pop()
                current_module = ensure_module(current_name, record.crate)
                pending_attributes: list[bytes] = []
                nested: list[tuple[Node, str, bool]] = []
                for child in current_parent.children:
                    if child.type == "attribute_item":
                        pending_attributes.append(source[child.start_byte : child.end_byte])
                        continue
                    if _is_comment(child):
                        current_module.todo_count += len(_TODO.findall(source[child.start_byte : child.end_byte]))
                        continue
                    if child.type == "mod_item":
                        name_node = child.child_by_field_name("name")
                        if name_node:
                            mod_name = source[name_node.start_byte : name_node.end_byte].decode("utf-8", "replace")
                            child_module = _declared_child(current_name, record, mod_name)
                            module_stats = ensure_module(child_module, record.crate)
                            if child_module not in current_module.declared_dependencies:
                                current_module.declared_dependencies.append(child_module)
                            module_stats.dependency_files.add(record.path.as_posix())
                            is_test = test_scope or (
                                _has_attribute(pending_attributes, "cfg")
                                and any(b"test" in attr for attr in pending_attributes)
                            )
                            if is_test:
                                module_stats.test_targets.add(current_name)
                            body = next((node for node in child.children if node.type == "declaration_list"), None)
                            if body is not None:
                                nested.append((body, child_module, is_test))
                        pending_attributes.clear()
                        continue
                    if child.type == "function_item":
                        stats = ensure_module(current_name, record.crate)
                        stats.function_count += 1
                        function_name = child.child_by_field_name("name")
                        if function_name and source[function_name.start_byte : function_name.end_byte] == b"main":
                            entry_targets = dict(_crate_roots(str(record.crate_dir)))
                            relative_file = record.path.relative_to(record.crate_dir).as_posix()
                            stats.contains_main = stats.contains_main or (
                                relative_file in entry_targets and entry_targets[relative_file] != "lib"
                            )
                        if _visible(child, source):
                            stats.public_function_count += 1
                        is_test = test_scope or in_tests_dir or _has_attribute(pending_attributes, "test")
                        if is_test:
                            stats.test_function_count += 1
                        stats.raw_complexity += _count_function_branches(child, source)
                        descendants = list(child.children)
                        while descendants:
                            descendant = descendants.pop()
                            if descendant.type == "unsafe_block":
                                stats.unsafe_count += 1
                            elif _is_comment(descendant):
                                stats.todo_count += len(_TODO.findall(source[descendant.start_byte : descendant.end_byte]))
                            elif descendant.type == "macro_invocation":
                                macro = source[descendant.start_byte : min(descendant.end_byte, descendant.start_byte + 64)]
                                if re.match(rb"(?:todo|unimplemented)\s*!", macro):
                                    stats.todo_count += 1
                            descendants.extend(descendant.children)
                        modifiers = next((n for n in child.children if n.type == "function_modifiers"), None)
                        if modifiers and b"unsafe" in source[modifiers.start_byte : modifiers.end_byte]:
                            stats.unsafe_count += 1
                        pending_attributes.clear()
                        continue
                    if child.type == "unsafe_block":
                        current_module.unsafe_count += 1
                    elif child.type == "impl_item" and any(node.type == "unsafe" for node in child.children):
                        current_module.unsafe_count += 1
                    elif child.type == "macro_invocation":
                        macro = source[child.start_byte : min(child.end_byte, child.start_byte + 64)]
                        if re.match(rb"(?:todo|unimplemented)\s*!", macro):
                            current_module.todo_count += 1
                    nested.extend((descendant, current_name, test_scope) for descendant in child.children)
                    pending_attributes.clear()
                stack.extend(reversed(nested))

        # Module-specific line totals are assigned from the deepest inline
        # module span, with the file's outer module owning all remaining lines.
        scopes: list[tuple[int, int, str]] = [(tree.root_node.start_point.row, tree.root_node.end_point.row + 1, record.module)]

        scope_stack = [(tree.root_node, record.module)]
        while scope_stack:
            node, current_name = scope_stack.pop()
            for child in reversed(node.children):
                if child.type == "mod_item":
                    name_node = child.child_by_field_name("name")
                    body = next((item for item in child.children if item.type == "declaration_list"), None)
                    if name_node and body:
                        mod_name = source[name_node.start_byte : name_node.end_byte].decode("utf-8", "replace")
                        scope_module_name = _declared_child(current_name, record, mod_name)
                        scopes.append((body.start_point.row, body.end_point.row + 1, scope_module_name))
                        scope_stack.append((body, scope_module_name))
                else:
                    scope_stack.append((child, current_name))
        lines = source.splitlines()
        for index, line in enumerate(lines):
            stripped = line.strip()
            if not stripped or stripped.startswith((b"//", b"/*", b"*", b"*/")):
                continue
            owner = min(
                (scope for scope in scopes if scope[0] <= index < scope[1]),
                key=lambda scope: scope[1] - scope[0],
                default=(0, len(lines), record.module),
            )[2]
            ensure_module(owner, record.crate).loc += 1

        # Visit root tree with sibling attributes retained for the immediately
        # following declaration.
        visit(tree.root_node, record.module)

    # Resolve source references against the complete module tree, keeping the
    # first actual reference before declaration-order fallbacks.
    known = set(modules)
    ref_parser = Parser(_RUST)
    for record in file_records:
        tree = ref_parser.parse(record.source)
        if tree is None:
            continue
        ref_stack = [(tree.root_node, record.module)]
        while ref_stack:
            node, current_name = ref_stack.pop()
            if node.type in {"scoped_identifier", "scoped_type_identifier", "scoped_use_list", "use_declaration"}:
                text = record.source[node.start_byte : node.end_byte].decode("utf-8", "replace")
                for target in _resolve_source_references(text, current_name, record.crate, known):
                    if target:
                        modules[current_name].add_dependency(target)
            if node.type == "mod_item":
                name_node = node.child_by_field_name("name")
                if name_node:
                    inner = record.source[name_node.start_byte : name_node.end_byte].decode("utf-8", "replace")
                    child_name = _declared_child(current_name, record, inner)
                    body = next((item for item in node.children if item.type == "declaration_list"), None)
                    if body:
                        ref_stack.append((body, child_name))
                    continue
            ref_stack.extend((child, current_name) for child in reversed(node.children))

    for module in modules.values():
        for dependency in module.declared_dependencies:
            module.add_dependency(dependency)
        module.dependencies = list(dict.fromkeys(dep for dep in module.dependencies if dep in known and dep != module.name))
        if module.test_function_count:
            module.test_targets.update(module.dependencies)

    aliases = _compress_modules(modules)
    # Canonicalize all graph edges after small-module aggregation.
    for module in modules.values():
        module.dependencies = list(
            dict.fromkeys(
                aliases.get(dep, dep)
                for dep in module.dependencies
                if aliases.get(dep, dep) in modules and aliases.get(dep, dep) != module.name
            )
        )
        module.declared_dependencies = list(
            dict.fromkeys(
                aliases.get(dep, dep)
                for dep in module.declared_dependencies
                if aliases.get(dep, dep) in modules and aliases.get(dep, dep) != module.name
            )
        )
        module.test_targets = {aliases.get(target, target) for target in module.test_targets}

    lcov_values: dict[str, list[tuple[int, int]]] = defaultdict(list)
    if lcov:
        for old_name, rows in _parse_lcov(Path(lcov).expanduser().resolve(), root, file_to_modules).items():
            lcov_values[aliases.get(old_name, old_name)].extend(rows)
    raw_complexity = {name: module.raw_complexity for name, module in modules.items()}
    normalized = _normalize_complexities(raw_complexity)
    depended_by = {name: 0 for name in modules}
    for module in modules.values():
        for dependency in module.dependencies:
            depended_by[dependency] += 1

    proxy_test_counts = {name: module.test_function_count for name, module in modules.items()}
    for test_module in modules.values():
        if test_module.test_function_count:
            for target in test_module.test_targets:
                if target in proxy_test_counts:
                    proxy_test_counts[target] += test_module.test_function_count

    module_profiles = []
    for module in sorted(modules.values(), key=lambda item: (item.declaration_order, item.name)):
        if module.loc <= 0:
            continue
        if lcov:
            coverage_rows = lcov_values.get(module.name, module.line_coverage)
            coverage = sum(hit for _, hit in coverage_rows) / len(coverage_rows) if coverage_rows else 0.0
        else:
            coverage = min(1.0, proxy_test_counts[module.name] / max(1, module.public_function_count))
        module_profiles.append(
            {
                "name": module.name,
                "loc": module.loc,
                "complexity": round(normalized.get(module.name, 0.0), 6),
                "unsafe_count": module.unsafe_count,
                "depends_on": module.dependencies,
                "depended_by_count": depended_by[module.name],
                "test_coverage": round(coverage, 6),
                "todo_count": module.todo_count,
            }
        )

    if not module_profiles:
        raise ValueError("Rust source files contained no non-comment code lines.")
    profile_names = {item["name"] for item in module_profiles}
    module_profiles = [item for item in module_profiles if item["name"] in profile_names]
    total_loc = sum(item["loc"] for item in module_profiles)
    total_unsafe = sum(item["unsafe_count"] for item in module_profiles)
    total_functions = sum(modules[item["name"]].function_count for item in module_profiles)
    unsafe_ratio = total_unsafe / max(1, total_unsafe + total_functions)
    raw_complexity_total = sum(modules[item["name"]].raw_complexity for item in module_profiles)
    complexity_per_function = raw_complexity_total / max(1, total_functions)
    # A sigmoid of absolute branch complexity per function is comparable across
    # repositories. Module-level values above remain locally normalized for shading.
    calibrated = (complexity_per_function - 2.0) / 2.0
    avg_complexity = 1.0 / (1.0 + math.exp(-max(-60.0, min(60.0, calibrated))))
    coverage_weight = sum(modules[item["name"]].public_function_count for item in module_profiles)
    if coverage_weight:
        test_coverage = sum(
            item["test_coverage"] * modules[item["name"]].public_function_count
            for item in module_profiles
        ) / coverage_weight
    else:
        test_coverage = sum(item["test_coverage"] for item in module_profiles) / len(module_profiles)

    entry_module = None
    if entry:
        entry_module = next(
            (item["name"] for item in module_profiles if item["name"] == entry or item["name"].endswith("::" + entry)),
            None,
        )
        if not entry_module:
            raise ValueError(f"Entry module not found: {entry}")
    else:
        main_candidates = [
            item["name"]
            for item in module_profiles
            if modules[item["name"]].contains_main and modules[item["name"]].crate == root_crate
        ]
        if not main_candidates:
            main_candidates = [item["name"] for item in module_profiles if modules[item["name"]].contains_main]
        entry_module = next(
            iter(main_candidates),
            None,
        )
        entry_module = entry_module or next(
            (item["name"] for item in module_profiles if modules[item["name"]].contains_main),
            next((item["name"] for item in module_profiles if item["name"].endswith("::main")), None),
        )
    library_declaration_order = not entry_module and not any(
        modules[item["name"]].contains_main for item in module_profiles
    )
    if entry_module:
        start_module = entry_module
    else:
        start_module = next((item["name"] for item in module_profiles if item["name"].endswith("::lib")), module_profiles[0]["name"])

    # Deterministic DFS in first-reference order. A repeated entry is retained
    # only for an actual back-edge to a node on the current recursion stack.
    call_path: list[str] = []
    visited: set[str] = set()
    active: set[str] = set()

    def dfs(module_name: str) -> None:
        if len(call_path) >= 16:
            return
        if module_name in active:
            call_path.append(module_name)
            return
        if module_name in visited:
            return
        if module_name not in profile_names:
            return
        visited.add(module_name)
        active.add(module_name)
        call_path.append(module_name)
        dependencies = modules[module_name].dependencies
        if library_declaration_order:
            dependencies = list(dict.fromkeys(modules[module_name].declared_dependencies + dependencies))
        for dependency in dependencies:
            dfs(dependency)
        active.remove(module_name)

    dfs(start_module)
    for item in module_profiles:
        if len(call_path) >= 16:
            break
        dfs(item["name"])

    rust_feature_counts["total_loc"] = total_loc
    rust_features = _rust_feature_profile(rust_feature_counts, modules, depended_by)
    repo_fingerprint = make_repo_fingerprint(root_crate, module_profiles)
    result = {
        "name": name or root.name or "rust-project",
        "repo_fingerprint": repo_fingerprint,
        "global": {
            "total_loc": total_loc,
            "unsafe_ratio": round(unsafe_ratio, 6),
            "test_coverage": round(test_coverage, 6),
            "avg_complexity": round(avg_complexity, 6),
        },
        "rust_features": rust_features,
        "modules": module_profiles,
        "call_path": call_path,
        "coverage_source": "lcov" if lcov else "proxy",
    }
    # Validate through the existing profile boundary; unknown optional metadata
    # is intentionally ignored by older composer clients.
    temp_profile = json.dumps(result, sort_keys=True, indent=2)
    from tempfile import NamedTemporaryFile

    with NamedTemporaryFile("w", encoding="utf-8", suffix=".json", delete=False) as handle:
        handle.write(temp_profile)
        check_path = Path(handle.name)
    try:
        load_profile(check_path)
    finally:
        check_path.unlink(missing_ok=True)
    return result


def format_summary(profile: dict) -> str:
    lines = [
        f"Profile: {profile['name']} | LOC {profile['global']['total_loc']} | "
        f"unsafe {profile['global']['unsafe_ratio']:.4f} | "
        f"complexity {profile['global']['avg_complexity']:.2f} | "
        f"coverage {profile['global']['test_coverage']:.2f} ({profile['coverage_source']})",
        f"{'Module':42} {'Complexity rank':>15} {'Unsafe':>6} {'TODO':>5} {'Coverage':>9} {'Uses':>5}",
        "-" * 92,
    ]
    for module in profile["modules"]:
        lines.append(
            f"{module['name'][:42]:42} {module['complexity']:15.2f} "
            f"{module['unsafe_count']:6d} {module['todo_count']:5d} "
            f"{module['test_coverage']:9.2f} {module['depended_by_count']:5d}"
        )
    lines.append("call_path: " + " -> ".join(profile["call_path"]))
    return "\n".join(lines)


def format_explanation(profile: dict) -> str:
    lines = ["Metric-to-music explanation:"]
    for module in profile["modules"]:
        decisions = [
            f"LOC {module['loc']} -> section pacing/length",
            f"complexity {module['complexity']:.2f} -> intensity shading and rhythm/register density",
            f"depends_on {', '.join(module['depends_on']) or 'none'} -> call-path order",
        ]
        if module["complexity"] >= 0.7:
            decisions.append("hotspot: higher violin register, busier drums/guitar, section lift")
        if module["unsafe_count"]:
            decisions.append("unsafe: diminished/tritone color and violin tremolo")
        else:
            decisions.append("unsafe: no altered harmony/tremolo moment")
        decisions.append("coverage: " + ("resolved cadence" if module["test_coverage"] >= 0.55 else "open cadence"))
        if module["todo_count"]:
            decisions.append("TODO: brief rest/sus4 suspension")
        else:
            decisions.append("TODO: no added suspension/rest")
        decisions.append(
            f"depended_by_count {module['depended_by_count']} -> "
            + ("deeper, longer bass roots" if module["depended_by_count"] >= 4 else "normal bass support")
        )
        lines.append(
            f"{module['name']}: complexity={module['complexity']:.2f}, "
            f"unsafe={module['unsafe_count']}, todo={module['todo_count']}, "
            f"coverage={module['test_coverage']:.2f} -> " + "; ".join(decisions)
        )
    return "\n".join(lines)


def write_profile(profile: dict, destination: str | Path) -> Path:
    path = Path(destination)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(profile, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return path


def resolve_repository(source: str | Path) -> Path:
    """Resolve a local project or shallow-clone a URL into a stable cache path."""

    value = str(source)
    if not re.match(r"^(?:https?://|ssh://|git@)", value):
        path = Path(value).expanduser().resolve()
        if not path.is_dir():
            raise ValueError(f"Rust repository directory not found: {path}")
        return path
    url = value.rstrip("/")
    if url.endswith(".git"):
        slug = url[:-4].rsplit("/", 1)[-1]
    else:
        slug = url.rsplit("/", 1)[-1]
    slug = re.sub(r"[^A-Za-z0-9_.-]+", "_", slug) or "repository"
    digest = hashlib.sha256(url.encode("utf-8")).hexdigest()[:12]
    cache_root = Path.cwd() / "out" / ".repo-cache"
    destination = cache_root / f"{slug}-{digest}"
    if not destination.exists():
        cache_root.mkdir(parents=True, exist_ok=True)
        subprocess.run(
            ["git", "clone", "--depth", "1", "--", url, str(destination)],
            check=True,
        )
    return destination.resolve()


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m symphony.analyze", description="Analyze a Rust repository into a Symphony profile.")
    parser.add_argument("repository", help="Path to a local Rust repository.")
    parser.add_argument("--out", required=True, help="Profile JSON destination, e.g. profiles/my-project.json")
    parser.add_argument("--entry", help="Entry module name (defaults to main, then lib).")
    parser.add_argument("--lcov", help="LCOV coverage file; replaces proxy coverage.")
    parser.add_argument("--explain", action="store_true", help="Print module metrics and the musical decisions they drive.")
    args = parser.parse_args(argv)
    try:
        profile = analyze_repository(args.repository, entry=args.entry, lcov=args.lcov)
        path = write_profile(profile, args.out)
        print(format_summary(profile))
        print(f"profile: {path}")
        if args.explain:
            print(format_explanation(profile))
        return 0
    except (OSError, ValueError, subprocess.SubprocessError) as exc:
        print(f"symphony.analyze: error: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
